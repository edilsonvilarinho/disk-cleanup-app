import { describe, expect, it } from 'vitest'
import { translate } from '../i18n/i18n'
import { MESSAGES } from '../i18n/messages'
import { report } from '../test/fixtures'
import { CARD_PENDING_LIMIT, CARD_WIDTH, clip, escapeXml, reportCardFileName, reportCardSvg } from './reportCard'

const t = (key: string, params?: Record<string, string | number>) => translate(MESSAGES.pt, key, params)
const base = { report, t, locale: 'pt' as const, generatedAt: new Date(2026, 10, 23, 14, 48), volumeRoot: 'C:\\', version: '0.2.0' }

describe('reportCardSvg', () => {
  it('traz título, volume, KPIs, tiers, pendências e rodapé, em SVG sem foreignObject', () => {
    const { svg, width, height } = reportCardSvg(base)
    expect(width).toBe(CARD_WIDTH)
    expect(height).toBeGreaterThan(400)
    expect(svg.startsWith('<svg xmlns="http://www.w3.org/2000/svg"')).toBe(true)
    expect(svg).not.toContain('foreignObject')
    expect(svg).toContain('Relatório da limpeza')
    expect(svg).toContain('C:\\ · 23/11/2026')
    expect(svg).toContain('+24,8 GB')
    expect(svg).toContain('A · Cache')
    expect(svg).toContain('C · Regeneráveis')
    expect(svg).toContain(report.pending[0]!.label.pt)
    expect(svg).toContain('Gerado pelo Disk Cleanup v0.2.0')
  })

  it('escapa texto de dado e limita as pendências', () => {
    const item = { ...report.pending[0]!, label: { pt: '<script>&"x"</script>', en: 'x' } }
    const many = { ...report, pending: Array.from({ length: CARD_PENDING_LIMIT + 3 }, (_, i) => ({ ...item, id: `p${i}` })) }
    const { svg } = reportCardSvg({ ...base, report: many })
    expect(svg).not.toContain('<script>')
    expect(svg).toContain('&lt;script&gt;&amp;&quot;x&quot;&lt;/script&gt;')
    expect(svg.match(/<circle /g)).toHaveLength(CARD_PENDING_LIMIT)
    expect(svg).toContain('+3 pendências')
  })

  it('sem pendências, sem tiers liberados e sem versão', () => {
    const empty = { ...report, pending: [], runs: report.runs.map((r) => ({ ...r, freedBytes: 0, estimatedBytes: 0 })) }
    const { svg } = reportCardSvg({ ...base, report: empty, version: null, locale: 'en', t: (k, p) => translate(MESSAGES.en, k, p) })
    expect(svg).toContain('Nothing pending.')
    expect(svg).toContain('Generated by Disk Cleanup</text>')
    // Barra de tier sem valor não desenha preenchimento: só o trilho.
    expect(svg.match(/fill="#0D9488"/g)).toHaveLength(1)
  })
})

describe('auxiliares', () => {
  it('escapa os cinco caracteres de XML', () => {
    expect(escapeXml(`a&b<c>d"e'f`)).toBe('a&amp;b&lt;c&gt;d&quot;e&apos;f')
  })

  it('corta texto longo com reticências', () => {
    expect(clip('abc', 3)).toBe('abc')
    expect(clip('abcdef', 4)).toBe('abc…')
  })

  it('nome do arquivo com a data local', () => {
    expect(reportCardFileName('disk-cleanup-relatorio', new Date(2026, 0, 5, 23, 59))).toBe('disk-cleanup-relatorio-2026-01-05.png')
  })
})
